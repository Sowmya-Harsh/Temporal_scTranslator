def model_of(name):
    if "film_pre" in name: return "film_pre"
    if "film_post" in name: return "film_post"
    return "mlp"

colors = {"mlp": "#8899aa", "film_pre": "#4C72B0", "film_post": "#DD8452"}

# compute averages
names, avg_r, avg_ccc, cols = [], [], [], []
for name, vals in results.items():
    rs = [v[0] for v in vals]
    ccs = [v[1] for v in vals]
    names.append(name)
    avg_r.append(np.mean(rs))
    avg_ccc.append(np.mean(ccs))
    cols.append(colors[model_of(name)])

# sort by avg ccc descending
order = np.argsort(avg_ccc)[::-1]
names = [names[i] for i in order]
avg_r = [avg_r[i] for i in order]
avg_ccc = [avg_ccc[i] for i in order]
cols = [cols[i] for i in order]

fig, ax = plt.subplots(figsize=(9, 12))
y = np.arange(len(names))
bar_h = 0.38

ax.barh(y + bar_h/2, avg_r, height=bar_h, color=cols, alpha=0.9, label="mean Pearson R")
ax.barh(y - bar_h/2, avg_ccc, height=bar_h, color=cols, alpha=0.5, label="mean CCC")

ax.set_yticks(y)
ax.set_yticklabels(names, fontsize=8)
ax.invert_yaxis()
ax.set_xlabel("Score (averaged across all 10 timepoint pairs)")
ax.set_title("Sweep results: mean Pearson R / CCC per config\n(sorted by mean CCC, color = model type)")
ax.axvline(0, color="black", linewidth=0.8)
ax.grid(axis="x", alpha=0.3)

from matplotlib.patches import Patch
legend_elems = [
    Patch(facecolor=colors["mlp"], label="mlp"),
    Patch(facecolor=colors["film_pre"], label="film_pre"),
    Patch(facecolor=colors["film_post"], label="film_post"),
    Patch(facecolor="gray", alpha=0.9, label="solid bar = mean R"),
    Patch(facecolor="gray", alpha=0.5, label="light bar = mean CCC"),
]
ax.legend(handles=legend_elems, loc="lower right", fontsize=8)

plt.tight_layout()
